-- Additive admission control. Install only while every writer is stopped (DDL is not transactional).
CREATE TABLE FANTASY_ESCRITA_TRANSICAO (
 OPERACAO_ID CHAR(36) NOT NULL PRIMARY KEY,
 TEMPORADA SMALLINT UNSIGNED NOT NULL,
 RODADA TINYINT UNSIGNED NOT NULL,
 ACAO ENUM('INICIALIZAR','TRANSICIONAR','RECUPERAR') NOT NULL,
 ORIGEM ENUM('LEGADO','BLOQUEADO','ATUAL') NULL,
 DESTINO ENUM('LEGADO','BLOQUEADO','ATUAL') NOT NULL,
 GERACAO_BASE BIGINT UNSIGNED NOT NULL,
 FENCE_BASE BIGINT UNSIGNED NOT NULL,
 REVISAO_BASE BIGINT UNSIGNED NOT NULL,
 HASH_BASE CHAR(64) NULL,
 OPERADOR VARCHAR(100) NOT NULL,
 JUSTIFICATIVA VARCHAR(1000) NOT NULL,
 CRIADA_EM DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 CONSTRAINT FET_ESCOPO_FK FOREIGN KEY (TEMPORADA,RODADA) REFERENCES FANTASY_APURACAO_RODADA(TEMPORADA,RODADA) ON DELETE RESTRICT ON UPDATE RESTRICT
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE TABLE FANTASY_ESCRITA_CONTROLE (
 TEMPORADA SMALLINT UNSIGNED NOT NULL,
 RODADA TINYINT UNSIGNED NOT NULL,
 MODO ENUM('LEGADO','BLOQUEADO','ATUAL') NOT NULL,
 GERACAO BIGINT UNSIGNED NOT NULL DEFAULT 0,
 ATUAL_JA_HABILITADO BOOLEAN NOT NULL DEFAULT FALSE,
 ULTIMA_TRANSICAO_ID CHAR(36) NOT NULL,
 PRIMARY KEY(TEMPORADA,RODADA),
 CONSTRAINT FEC_ESCOPO_FK FOREIGN KEY(TEMPORADA,RODADA) REFERENCES FANTASY_APURACAO_RODADA(TEMPORADA,RODADA) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT FEC_AUDITORIA_FK FOREIGN KEY(ULTIMA_TRANSICAO_ID) REFERENCES FANTASY_ESCRITA_TRANSICAO(OPERACAO_ID) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT FEC_GERACAO_CHECK CHECK (ATUAL_JA_HABILITADO IN (0,1))
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

DELIMITER $$
-- Definer metadata check avoids granting TRIGGER/DDL privileges to collector accounts.
CREATE PROCEDURE FANTASY_VERIFY_ADMISSION()
SQL SECURITY DEFINER
BEGIN
 DECLARE n INT;
 SELECT COUNT(*) INTO n FROM information_schema.TRIGGERS WHERE TRIGGER_SCHEMA=DATABASE() AND TRIGGER_NAME IN
 ('FET_IMUTAVEL_UPDATE','FET_IMUTAVEL_DELETE','FEC_IMUTAVEL_DELETE','FEC_INICIAL','FEC_TRANSICAO',
 'FPS_ADMISSAO','FPS_IMUTAVEL_UPDATE','FPS_IMUTAVEL_DELETE','FPAS_ADMISSAO','FPAS_IMUTAVEL_UPDATE','FPAS_IMUTAVEL_DELETE',
 'FPC_ADMISSAO_INSERT','FPC_ADMISSAO_UPDATE','FPC_ADMISSAO_DELETE','FPA_ADMISSAO_INSERT','FPA_ADMISSAO_UPDATE','FPA_ADMISSAO_DELETE','FAR_ESCRITA_UPDATE');
 IF n<>18 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='ADMISSION_GUARDS_INCOMPLETE'; END IF;
 SELECT COUNT(*) INTO n FROM information_schema.ROUTINES WHERE ROUTINE_SCHEMA=DATABASE() AND ROUTINE_NAME IN
 ('FANTASY_ASSERT_WRITER','FANTASY_ASSERT_COLLECTION','FANTASY_VERIFY_ADMISSION');
 IF n<>3 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='ADMISSION_GUARDS_INCOMPLETE'; END IF;
END$$
CREATE TRIGGER FET_IMUTAVEL_UPDATE BEFORE UPDATE ON FANTASY_ESCRITA_TRANSICAO FOR EACH ROW
BEGIN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='ADMISSION_AUDIT_IMMUTABLE'; END$$
CREATE TRIGGER FET_IMUTAVEL_DELETE BEFORE DELETE ON FANTASY_ESCRITA_TRANSICAO FOR EACH ROW
BEGIN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='ADMISSION_AUDIT_IMMUTABLE'; END$$
CREATE TRIGGER FEC_IMUTAVEL_DELETE BEFORE DELETE ON FANTASY_ESCRITA_CONTROLE FOR EACH ROW
BEGIN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='ADMISSION_CONTROL_IMMUTABLE'; END$$
CREATE TRIGGER FEC_INICIAL BEFORE INSERT ON FANTASY_ESCRITA_CONTROLE FOR EACH ROW
BEGIN
 DECLARE n INT DEFAULT 0;
 SELECT COUNT(*) INTO n FROM FANTASY_ESCRITA_TRANSICAO t WHERE t.OPERACAO_ID=NEW.ULTIMA_TRANSICAO_ID
  AND t.TEMPORADA=NEW.TEMPORADA AND t.RODADA=NEW.RODADA AND t.ACAO='INICIALIZAR' AND t.ORIGEM IS NULL AND t.DESTINO='LEGADO' AND t.GERACAO_BASE=0;
 IF NEW.MODO<>'LEGADO' OR NEW.GERACAO<>0 OR NEW.ATUAL_JA_HABILITADO<>0 OR n<>1 THEN
  SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='ADMISSION_INITIALIZATION_INVALID';
 END IF;
END$$
CREATE TRIGGER FEC_TRANSICAO BEFORE UPDATE ON FANTASY_ESCRITA_CONTROLE FOR EACH ROW
BEGIN
 DECLARE n INT DEFAULT 0;
 DECLARE live_count INT DEFAULT 0;
 IF NEW.TEMPORADA<>OLD.TEMPORADA OR NEW.RODADA<>OLD.RODADA OR NEW.GERACAO<>OLD.GERACAO+1
  OR NOT ((OLD.MODO='LEGADO' AND NEW.MODO='BLOQUEADO') OR (OLD.MODO='BLOQUEADO' AND NEW.MODO='ATUAL') OR (OLD.MODO='ATUAL' AND NEW.MODO='BLOQUEADO'))
  OR NEW.ATUAL_JA_HABILITADO<>(OLD.ATUAL_JA_HABILITADO OR NEW.MODO='ATUAL') THEN
  SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='ADMISSION_TRANSITION_INVALID';
 END IF;
 SELECT COUNT(*) INTO n FROM FANTASY_ESCRITA_TRANSICAO t JOIN FANTASY_APURACAO_RODADA r
  ON r.TEMPORADA=t.TEMPORADA AND r.RODADA=t.RODADA WHERE t.OPERACAO_ID=NEW.ULTIMA_TRANSICAO_ID
  AND t.TEMPORADA=OLD.TEMPORADA AND t.RODADA=OLD.RODADA AND t.ORIGEM=OLD.MODO AND t.DESTINO=NEW.MODO
  AND t.ACAO='TRANSICIONAR' AND t.GERACAO_BASE=OLD.GERACAO AND t.FENCE_BASE=r.FENCE AND t.REVISAO_BASE=r.REVISAO_ATUAL AND (t.HASH_BASE<=>r.HASH_CONTEUDO_ATUAL);
 IF n<>1 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='ADMISSION_REFERENCE_MISMATCH'; END IF;
 IF NEW.MODO='ATUAL' THEN
  SELECT COUNT(*) INTO live_count FROM FANTASY_APURACAO_RODADA r WHERE r.TEMPORADA=OLD.TEMPORADA AND r.RODADA=OLD.RODADA
   AND (r.LOCK_TOKEN IS NOT NULL OR (r.REVISAO_ATUAL>0 AND r.ULTIMA_COLETA_APLICADA_ID IS NULL)
    OR (r.REVISAO_ATUAL=0 AND (EXISTS (SELECT 1 FROM FANTASY_PONTUACAO_SNAPSHOT s WHERE s.RODADA_ID=r.ID)
     OR EXISTS (SELECT 1 FROM FANTASY_PONTUACAO_ATLETA a WHERE a.APURACAO_ID=r.ID)
     OR EXISTS (SELECT 1 FROM FANTASY_PONTUACAO_COLETA a WHERE a.RODADA_ID=r.ID AND a.ESTADO='SUCESSO'))));
  SELECT live_count+COUNT(*) INTO live_count FROM FANTASY_PONTUACAO_COLETA c JOIN FANTASY_APURACAO_RODADA r ON r.ID=c.RODADA_ID
   WHERE r.TEMPORADA=OLD.TEMPORADA AND r.RODADA=OLD.RODADA AND c.ESTADO='EM_ANDAMENTO';
  IF live_count<>0 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='ADMISSION_NOT_QUIESCENT_OR_BACKFILLED'; END IF;
 END IF;
END$$

-- Every writer, including binaries that do not know admission, must pass these guards.
CREATE PROCEDURE FANTASY_ASSERT_WRITER(IN round_id INT UNSIGNED, IN writer_mode VARCHAR(10))
SQL SECURITY DEFINER
BEGIN
 DECLARE admitted VARCHAR(10) DEFAULT NULL;
 DECLARE season_id SMALLINT UNSIGNED;
 DECLARE round_number TINYINT UNSIGNED;
 -- A round trigger cannot SELECT ... FOR UPDATE its own mutating table (MySQL 1442).
 SELECT TEMPORADA,RODADA INTO season_id,round_number FROM FANTASY_APURACAO_RODADA WHERE ID=round_id;
 SELECT MODO INTO admitted FROM FANTASY_ESCRITA_CONTROLE WHERE TEMPORADA=season_id AND RODADA=round_number FOR UPDATE;
 IF admitted IS NULL OR admitted<>writer_mode THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='ADMISSION_WRITER_BLOCKED'; END IF;
END$$
CREATE TRIGGER FPS_ADMISSAO BEFORE INSERT ON FANTASY_PONTUACAO_SNAPSHOT FOR EACH ROW
BEGIN CALL FANTASY_ASSERT_WRITER(NEW.RODADA_ID,'LEGADO'); END$$
CREATE TRIGGER FPS_IMUTAVEL_UPDATE BEFORE UPDATE ON FANTASY_PONTUACAO_SNAPSHOT FOR EACH ROW
BEGIN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='SNAPSHOT_IMMUTABLE'; END$$
CREATE TRIGGER FPS_IMUTAVEL_DELETE BEFORE DELETE ON FANTASY_PONTUACAO_SNAPSHOT FOR EACH ROW
