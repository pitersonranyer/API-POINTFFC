CREATE TRIGGER FPAS_ADMISSAO BEFORE INSERT ON FANTASY_PONTUACAO_ATLETA_SNAPSHOT FOR EACH ROW
BEGIN
 DECLARE rid INT UNSIGNED;
 SELECT RODADA_ID INTO rid FROM FANTASY_PONTUACAO_SNAPSHOT WHERE ID=NEW.SNAPSHOT_ID;
 CALL FANTASY_ASSERT_WRITER(rid,'LEGADO');
END$$
