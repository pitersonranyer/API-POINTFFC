CREATE TABLE `FUTEBOL_COMPETICAO` (
  `ID` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
  `EXTERNAL_ID` INTEGER UNSIGNED NOT NULL,
  `CODIGO` VARCHAR(10) NOT NULL,
  `NOME` VARCHAR(255) NOT NULL,
  `PAIS` VARCHAR(100) NOT NULL,
  `TIPO` VARCHAR(50) NOT NULL,
  `EMBLEMA_URL` TEXT NULL,
  `TEMPORADA_ATUAL` SMALLINT UNSIGNED NOT NULL,
  `ATIVA` BOOLEAN NOT NULL DEFAULT true,
  `CRIADO_EM` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `ATUALIZADO_EM` DATETIME(3) NOT NULL,
  PRIMARY KEY (`ID`),
  UNIQUE INDEX `FUTEBOL_COMPETICAO_EXTERNAL_ID_key` (`EXTERNAL_ID`),
  UNIQUE INDEX `FUTEBOL_COMPETICAO_CODIGO_key` (`CODIGO`)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `FUTEBOL_TIME` (
  `ID` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
  `EXTERNAL_ID` INTEGER UNSIGNED NOT NULL,
  `NOME` VARCHAR(255) NOT NULL,
  `NOME_CURTO` VARCHAR(255) NULL,
  `SIGLA` VARCHAR(10) NULL,
  `ESCUDO_URL` TEXT NULL,
  `PAIS` VARCHAR(100) NOT NULL,
  `CRIADO_EM` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `ATUALIZADO_EM` DATETIME(3) NOT NULL,
  PRIMARY KEY (`ID`),
  UNIQUE INDEX `FUTEBOL_TIME_EXTERNAL_ID_key` (`EXTERNAL_ID`)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `FUTEBOL_PARTIDA` (
  `ID` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
  `EXTERNAL_ID` INTEGER UNSIGNED NOT NULL,
  `COMPETICAO_ID` INTEGER UNSIGNED NOT NULL,
  `TEMPORADA` SMALLINT UNSIGNED NOT NULL,
  `RODADA` SMALLINT UNSIGNED NULL,
  `FASE` VARCHAR(100) NULL,
  `GRUPO` VARCHAR(100) NULL,
  `TIME_MANDANTE_ID` INTEGER UNSIGNED NOT NULL,
  `TIME_VISITANTE_ID` INTEGER UNSIGNED NOT NULL,
  `DATA_HORA_UTC` DATETIME(3) NOT NULL,
  `STATUS` VARCHAR(50) NOT NULL,
  `VENCEDOR` VARCHAR(50) NULL,
  `PLACAR_MANDANTE` SMALLINT UNSIGNED NULL,
  `PLACAR_VISITANTE` SMALLINT UNSIGNED NULL,
  `PLACAR_INTERVALO_MANDANTE` SMALLINT UNSIGNED NULL,
  `PLACAR_INTERVALO_VISITANTE` SMALLINT UNSIGNED NULL,
  `ULTIMA_ATUALIZACAO_API` DATETIME(3) NOT NULL,
  `CRIADO_EM` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `ATUALIZADO_EM` DATETIME(3) NOT NULL,
  PRIMARY KEY (`ID`),
  UNIQUE INDEX `FUTEBOL_PARTIDA_EXTERNAL_ID_key` (`EXTERNAL_ID`),
  INDEX `FUTEBOL_PARTIDA_COMPETICAO_ID_TEMPORADA_RODADA_idx` (`COMPETICAO_ID`, `TEMPORADA`, `RODADA`),
  CONSTRAINT `FUTEBOL_PARTIDA_COMPETICAO_ID_fkey` FOREIGN KEY (`COMPETICAO_ID`) REFERENCES `FUTEBOL_COMPETICAO` (`ID`) ON DELETE RESTRICT ON UPDATE CASCADE,
  INDEX `FUTEBOL_PARTIDA_TIME_MANDANTE_ID_idx` (`TIME_MANDANTE_ID`),
  CONSTRAINT `FUTEBOL_PARTIDA_TIME_MANDANTE_ID_fkey` FOREIGN KEY (`TIME_MANDANTE_ID`) REFERENCES `FUTEBOL_TIME` (`ID`) ON DELETE RESTRICT ON UPDATE CASCADE,
  INDEX `FUTEBOL_PARTIDA_TIME_VISITANTE_ID_idx` (`TIME_VISITANTE_ID`),
  CONSTRAINT `FUTEBOL_PARTIDA_TIME_VISITANTE_ID_fkey` FOREIGN KEY (`TIME_VISITANTE_ID`) REFERENCES `FUTEBOL_TIME` (`ID`) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
