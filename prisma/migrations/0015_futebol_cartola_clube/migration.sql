ALTER TABLE `FUTEBOL_TIME` ADD COLUMN `CARTOLA_CLUBE_ID` INTEGER UNSIGNED NULL;

-- Enriquecer apenas clubes que participam de partidas BSA persistidas.
UPDATE `FUTEBOL_TIME` t SET t.`CARTOLA_CLUBE_ID` = CASE t.`EXTERNAL_ID`
  WHEN 1765 THEN 266
  WHEN 1766 THEN 282
  WHEN 1767 THEN 284
  WHEN 1768 THEN 293
  WHEN 1769 THEN 275
  WHEN 1770 THEN 263
  WHEN 1771 THEN 283
  WHEN 1772 THEN 315
  WHEN 1776 THEN 276
  WHEN 1777 THEN 265
  WHEN 1779 THEN 264
  WHEN 1780 THEN 267
  WHEN 1782 THEN 287
  WHEN 1783 THEN 262
  WHEN 4241 THEN 294
  WHEN 4286 THEN 280
  WHEN 4287 THEN 364
  WHEN 4364 THEN 2305
  WHEN 6684 THEN 285
  WHEN 6685 THEN 277
  ELSE t.`CARTOLA_CLUBE_ID` END
WHERE EXISTS (
  SELECT 1 FROM `FUTEBOL_PARTIDA` p
  JOIN `FUTEBOL_COMPETICAO` c ON c.`ID` = p.`COMPETICAO_ID`
  WHERE c.`CODIGO` = 'BSA'
    AND (p.`TIME_MANDANTE_ID` = t.`ID` OR p.`TIME_VISITANTE_ID` = t.`ID`)
);
