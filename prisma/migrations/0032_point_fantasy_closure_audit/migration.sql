-- One immutable audit per competition; no changes to existing data or columns.
CREATE TABLE `FANTASY_FECHAMENTO_AUDITORIA` (
  `COMPETICAO_ID` INTEGER UNSIGNED NOT NULL,
  `DADOS` JSON NOT NULL,
  PRIMARY KEY (`COMPETICAO_ID`),
  CONSTRAINT `FFA_COMPETICAO_fkey` FOREIGN KEY (`COMPETICAO_ID`) REFERENCES `FANTASY_COMPETICAO` (`ID`) ON DELETE RESTRICT ON UPDATE RESTRICT
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
