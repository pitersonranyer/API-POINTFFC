CREATE TABLE `FANTASY_INSCRICAO_OPERACAO` (
  `ID` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
  `USUARIO_ID` INTEGER UNSIGNED NOT NULL,
  `COMPETICAO_ID` INTEGER UNSIGNED NOT NULL,
  `CHAVE` VARCHAR(100) NOT NULL,
  `FINGERPRINT` CHAR(64) NOT NULL,
  `RESULTADO` JSON NOT NULL,
  `CRIADO_EM` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE INDEX `FIO_USUARIO_COMP_CHAVE_key` (`USUARIO_ID`, `COMPETICAO_ID`, `CHAVE`),
  UNIQUE INDEX `FIO_OWNER_key` (`ID`, `USUARIO_ID`, `COMPETICAO_ID`),
  PRIMARY KEY (`ID`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

ALTER TABLE `FANTASY_ESCALACAO`
  DROP CHECK `FANTASY_ESCALACAO_STATUS_CHECK`,
  ADD COLUMN `CONFIRMADA_EM` DATETIME(3) NULL,
  ADD COLUMN `INSCRICAO_OPERACAO_ID` INTEGER UNSIGNED NULL,
  ADD CONSTRAINT `FANTASY_ESCALACAO_STATUS_CHECK` CHECK (
    (`STATUS` = 'RASCUNHO' AND `CONFIRMADA_EM` IS NULL AND `INSCRICAO_OPERACAO_ID` IS NULL)
    OR (`STATUS` = 'INSCRITA' AND `CONFIRMADA_EM` IS NOT NULL AND `INSCRICAO_OPERACAO_ID` IS NOT NULL)
  ),
  ADD INDEX `FE_INSCRICAO_OWNER_idx` (`INSCRICAO_OPERACAO_ID`, `USUARIO_ID`, `COMPETICAO_ID`),
  ADD CONSTRAINT `FE_INSCRICAO_OPERACAO_fkey` FOREIGN KEY (`INSCRICAO_OPERACAO_ID`, `USUARIO_ID`, `COMPETICAO_ID`)
    REFERENCES `FANTASY_INSCRICAO_OPERACAO` (`ID`, `USUARIO_ID`, `COMPETICAO_ID`) ON DELETE RESTRICT ON UPDATE RESTRICT;
