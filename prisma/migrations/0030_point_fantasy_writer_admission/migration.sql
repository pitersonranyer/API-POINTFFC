CREATE PROCEDURE FANTASY_ASSERT_COLLECTION(IN rid INT UNSIGNED, IN model VARCHAR(20), IN endpoint VARCHAR(100), IN reason VARCHAR(255))
SQL SECURITY DEFINER
BEGIN
 DECLARE admitted VARCHAR(10) DEFAULT NULL;
 DECLARE rev BIGINT UNSIGNED;
 SELECT c.MODO,r.REVISAO_ATUAL INTO admitted,rev FROM FANTASY_ESCRITA_CONTROLE c JOIN FANTASY_APURACAO_RODADA r
  ON r.TEMPORADA=c.TEMPORADA AND r.RODADA=c.RODADA WHERE r.ID=rid FOR UPDATE;
 IF NOT ((admitted='LEGADO' AND model='SNAPSHOT_LEGADO') OR (admitted='ATUAL' AND model='ATUAL')
  OR (admitted='BLOQUEADO' AND model='ATUAL' AND endpoint='LOCAL_BACKFILL' AND reason LIKE 'BACKFILL_V1 %' AND rev=0))
  OR admitted IS NULL THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='ADMISSION_COLLECTION_BLOCKED'; END IF;
END$$
CREATE TRIGGER FPC_ADMISSAO_INSERT BEFORE INSERT ON FANTASY_PONTUACAO_COLETA FOR EACH ROW
BEGIN CALL FANTASY_ASSERT_COLLECTION(NEW.RODADA_ID,NEW.MODELO_PERSISTENCIA,NEW.ENDPOINT,NEW.MOTIVO); END$$
CREATE TRIGGER FPC_ADMISSAO_UPDATE BEFORE UPDATE ON FANTASY_PONTUACAO_COLETA FOR EACH ROW
BEGIN
 DECLARE admitted VARCHAR(10) DEFAULT NULL;
 DECLARE expired_count INT DEFAULT 0;
 SELECT c.MODO INTO admitted FROM FANTASY_ESCRITA_CONTROLE c JOIN FANTASY_APURACAO_RODADA r
  ON r.TEMPORADA=c.TEMPORADA AND r.RODADA=c.RODADA WHERE r.ID=OLD.RODADA_ID FOR UPDATE;
 IF NEW.RODADA_ID<>OLD.RODADA_ID OR NEW.MODELO_PERSISTENCIA<>OLD.MODELO_PERSISTENCIA OR NEW.OPERACAO_ID<>OLD.OPERACAO_ID THEN
  SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='ADMISSION_COLLECTION_IDENTITY'; END IF;
 -- Narrow expired-work recovery, never a scoring write or modification of a terminal operation.
 IF admitted='BLOQUEADO' AND OLD.ESTADO='EM_ANDAMENTO' AND NEW.ESTADO='INTERROMPIDA'
  AND NEW.ERRO_CODIGO='ADMISSION_EXPIRED_RECOVERY' AND NEW.SNAPSHOT_ID IS NULL AND NEW.REVISAO_RESULTANTE IS NULL THEN
  SELECT COUNT(*) INTO expired_count FROM FANTASY_APURACAO_RODADA r JOIN FANTASY_ESCRITA_CONTROLE c ON c.TEMPORADA=r.TEMPORADA AND c.RODADA=r.RODADA
   WHERE r.ID=OLD.RODADA_ID AND (r.LOCK_ATE IS NULL OR r.LOCK_ATE<=UTC_TIMESTAMP(3)) AND EXISTS
    (SELECT 1 FROM FANTASY_ESCRITA_TRANSICAO t WHERE t.TEMPORADA=c.TEMPORADA AND t.RODADA=c.RODADA AND t.ACAO='RECUPERAR'
     AND t.GERACAO_BASE=c.GERACAO AND t.FENCE_BASE=r.FENCE AND t.REVISAO_BASE=r.REVISAO_ATUAL AND (t.HASH_BASE<=>r.HASH_CONTEUDO_ATUAL));
  IF expired_count<>1 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='ADMISSION_LIVE_LEASE'; END IF;
 ELSE
  CALL FANTASY_ASSERT_COLLECTION(NEW.RODADA_ID,NEW.MODELO_PERSISTENCIA,NEW.ENDPOINT,NEW.MOTIVO);
 END IF;
END$$
CREATE TRIGGER FPC_ADMISSAO_DELETE BEFORE DELETE ON FANTASY_PONTUACAO_COLETA FOR EACH ROW
BEGIN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='COLLECTION_DELETE_FORBIDDEN'; END$$
CREATE TRIGGER FPA_ADMISSAO_INSERT BEFORE INSERT ON FANTASY_PONTUACAO_ATLETA FOR EACH ROW
BEGIN
 DECLARE origin_endpoint VARCHAR(100);
 DECLARE origin_reason VARCHAR(255);
 SELECT ENDPOINT,MOTIVO INTO origin_endpoint,origin_reason FROM FANTASY_PONTUACAO_COLETA WHERE ID=NEW.COLETA_ALTERACAO_ID;
 CALL FANTASY_ASSERT_COLLECTION(NEW.APURACAO_ID,'ATUAL',origin_endpoint,origin_reason);
END$$
CREATE TRIGGER FPA_ADMISSAO_UPDATE BEFORE UPDATE ON FANTASY_PONTUACAO_ATLETA FOR EACH ROW
BEGIN CALL FANTASY_ASSERT_WRITER(NEW.APURACAO_ID,'ATUAL'); END$$
CREATE TRIGGER FPA_ADMISSAO_DELETE BEFORE DELETE ON FANTASY_PONTUACAO_ATLETA FOR EACH ROW
BEGIN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='CURRENT_DELETE_FORBIDDEN'; END$$
CREATE TRIGGER FAR_ESCRITA_UPDATE BEFORE UPDATE ON FANTASY_APURACAO_RODADA FOR EACH ROW
BEGIN
 DECLARE admitted VARCHAR(10) DEFAULT NULL;
 SELECT MODO INTO admitted FROM FANTASY_ESCRITA_CONTROLE WHERE TEMPORADA=OLD.TEMPORADA AND RODADA=OLD.RODADA FOR UPDATE;
 IF NEW.ULTIMA_VERSAO_SNAPSHOT<>OLD.ULTIMA_VERSAO_SNAPSHOT THEN CALL FANTASY_ASSERT_WRITER(OLD.ID,'LEGADO'); END IF;
 IF NEW.REVISAO_ATUAL<>OLD.REVISAO_ATUAL OR NOT (NEW.HASH_CONTEUDO_ATUAL<=>OLD.HASH_CONTEUDO_ATUAL) THEN
  IF NOT (admitted='ATUAL' OR (admitted='BLOQUEADO' AND OLD.REVISAO_ATUAL=0 AND NEW.REVISAO_ATUAL=1)) OR admitted IS NULL THEN
   SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='ADMISSION_REVISION_BLOCKED';
  END IF;
 END IF;
END$$
